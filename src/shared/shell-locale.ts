export function shellText(language: ShellLanguage, key: ShellLocaleKey): string {
  return SHELL_LOCALE[language][key] ?? SHELL_LOCALE.vi[key];
}

export function shellNavigationLabel(language: ShellLanguage, key: string, fallback: string): string {
  if (language === 'vi') return fallback;
  const localeKey = `nav.${key === 'putaway-management' ? 'tray' : key}` as ShellLocaleKey;
  return localeKey in SHELL_LOCALE[language] ? shellText(language, localeKey) : fallback;
}

export function useShellUi() {
  const { language, theme, setLanguage, setTheme } = useShellPreferences();
  return {
    language,
    theme,
    setLanguage,
    setTheme,
    t: (key: ShellLocaleKey) => shellText(language, key),
    navLabel: (key: string, fallback = key) => shellNavigationLabel(language, key, fallback),
  };
}


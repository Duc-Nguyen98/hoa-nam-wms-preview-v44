/** Translate only the known UI-composed notices; keep interpolated dates and source text intact. */
export function catalogueNoticeCopy(translate: TranslateCopy, message: string): string {
  const periodPrefix = 'Chưa có dữ liệu cho kỳ vừa chọn. Đang hiển thị kỳ ';
  if (message.startsWith(periodPrefix) && message.endsWith('.')) {
    return translate('Chưa có dữ liệu cho kỳ vừa chọn. Đang hiển thị kỳ {period}.', { period: formatDeclaredDateText(message.slice(periodPrefix.length, -1), parseShellLanguage(translate('vi-VN'))) });
  }
  const retainedSuffix = ' Danh sách hiện tại được giữ nguyên.';
  if (message.endsWith(retainedSuffix)) return `${translate(message.slice(0, -retainedSuffix.length))} ${translate(retainedSuffix.trim())}`;
  const checkedPrefix = 'Đã kiểm tra dữ liệu. ';
  const blockedSuffix = ' API, quyền ghi và quy tắc nghiệp vụ chưa được cung cấp.';
  if (message.startsWith(checkedPrefix) && message.endsWith(blockedSuffix)) {
    return `${translate(checkedPrefix.trim())} ${translate(message.slice(checkedPrefix.length, -blockedSuffix.length))} ${translate(blockedSuffix.trim())}`;
  }
  return translate(message);
}

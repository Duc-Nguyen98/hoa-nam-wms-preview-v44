export type OperationsText = string | { template: string; values: Readonly<Record<string, OperationsText | number>> } | { parts: readonly OperationsText[]; separator: string };
export type OperationsNotice = Omit<NoticeFeedback, 'message'> & { message: OperationsText };

/** Raw interpolation values stay unchanged; nested uiText values explicitly mark UI copy. */
export const uiText = (template: string, values: Readonly<Record<string, OperationsText | number>> = {}): OperationsText => ({ template, values });
export const uiList = (parts: readonly (OperationsText | false | null | undefined)[], separator = '; '): OperationsText => ({ parts: parts.filter((part): part is OperationsText => Boolean(part)), separator });

export function renderOperationsText(message: OperationsText, tx: (value: string, values?: Readonly<Record<string, string | number>>) => string): string {
  if (typeof message === 'string') return tx(message);
  if ('parts' in message) return message.parts.map(part => renderOperationsText(part, tx)).join(message.separator);
  const values = Object.fromEntries(Object.entries(message.values).map(([key, value]) => [key, typeof value === 'object' ? renderOperationsText(value, tx) : value]));
  return tx(message.template, values);
}

/** Only authored scope-label templates are translated; supplied counts and other source text are preserved. */
export function operationsScopeLabel(value: string, tx: (value: string, values?: Readonly<Record<string, string | number>>) => string): string {
  const match = /^Phạm vi hiển thị: (\d+) (dòng tồn|phiếu) trong bộ nguồn đối chiếu\.$/.exec(value);
  return match ? tx(`Phạm vi hiển thị: {count} ${match[2]} trong bộ nguồn đối chiếu.`, { count: match[1] }) : tx(value);
}

type Translate = <Value>(value: Value, values?: Readonly<Record<string, string | number>>) => Value;
const patterns = Object.keys(REPORTS_EN_COPY).filter(key => /\{\w+\}/.test(key)).sort((left, right) => right.length - left.length).map(key => {
  const names: string[] = [];
  const source = key.split(/(\{\w+\})/g).map(part => /^\{\w+\}$/.test(part)
    ? (names.push(part.slice(1, -1)), '([\\s\\S]*?)') : part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('');
  return { key, names, expression: new RegExp(`^${source}$`) };
});

/** Also translates already-formatted notices without changing stored state or controller dependencies. */
export function translateReportCopy<Value>(value: Value, translate: Translate, values?: Readonly<Record<string, string | number>>): Value {
  if (typeof value !== 'string' || values || Object.hasOwn(REPORTS_EN_COPY, value)) return translate(value, values);
  const direct = translate(value);
  if (direct !== value) return direct;
  // Chart descriptions contain a series of independent, localized sentences.
  if (value.includes('; ')) {
    const parts = value.split('; ').map(part => translateReportCopy(part, translate));
    const joined = parts.join('; ');
    if (joined !== value) return joined as Value;
  }
  for (const pattern of patterns) {
    const match = pattern.expression.exec(value);
    if (!match) continue;
    const captures = Object.fromEntries(pattern.names.map((name, index) => [name, ['status', 'action', 'label', 'order', 'description'].includes(name) ? translateReportCopy(match[index + 1], translate) : match[index + 1]]));
    for (const name of ['date', 'period']) if (captures[name] !== undefined) captures[name] = formatDeclaredDateText(captures[name], parseShellLanguage(translate('vi-VN')));
    if (pattern.key === EXPORT_SUCCESS_NOTICE && /^\d+$/.test(captures.count)) {
      captures.count = Number(captures.count).toLocaleString(translate('vi-VN'));
    }
    return translate(pattern.key, captures) as Value;
  }
  return value;
}

export function useReportCopy() {
  const translate = useUiCopy(REPORTS_EN_COPY);
  return useCallback(<Value,>(value: Value, values?: Readonly<Record<string, string | number>>) => translateReportCopy(value, translate, values), [translate]);
}

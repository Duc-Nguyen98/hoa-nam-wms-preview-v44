/** Translate the approved presentation contract without changing its source fixture. */
export function translateAccountAuthCopy(copy: Readonly<AuthCopy>, tx: (value: string) => string): AuthCopy {
  return {
    ...copy,
    subtitle: tx(copy.subtitle), heading: copy.heading.map(tx), introduction: tx(copy.introduction),
    pillars: copy.pillars.map(tx), username: tx(copy.username), usernamePlaceholder: tx(copy.usernamePlaceholder),
    password: tx(copy.password), passwordPlaceholder: tx(copy.passwordPlaceholder),
    showPassword: tx(copy.showPassword), hidePassword: tx(copy.hidePassword),
    forgotPassword: tx(copy.forgotPassword), submit: tx(copy.submit),
    accessTitle: tx(copy.accessTitle), accessDescription: tx(copy.accessDescription), footer: tx(copy.footer),
  };
}
